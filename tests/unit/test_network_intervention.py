# T3-f: Repeated intervention (same band, different records)
# ---------------------------------------------------------------------------

class TestRepeatedIntervention:
    def test_two_records_with_different_bands(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec1 = _make_record(tc_handle="1:", latency_ms=100.0)
        rec2 = _make_record(tc_handle="2:", latency_ms=200.0)

        r1 = engine.apply(rec1)
        r2 = engine.apply(rec2)

        assert r1.status == NetworkInterventionStatus.APPLIED
        assert r2.status == NetworkInterventionStatus.APPLIED
        assert len(engine._active_records) == 2

    def test_rollback_all_removes_all_records(self):
        engine = NetworkInterventionEngine(dry_run=True)
        for band in (1, 2, 3):
            rec = _make_record(tc_handle=f"{band}:")
            engine.apply(rec)

        assert len(engine._active_records) == 3
        rolled = engine.rollback_all()
        assert len(rolled) == 3
        assert len(engine._active_records) == 0


