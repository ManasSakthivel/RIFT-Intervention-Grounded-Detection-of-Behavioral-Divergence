class TestInvalidStateHandling:
    def test_verify_on_non_applied_record_does_not_change_status(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:")
        # record is still PENDING (not applied)
        result = engine.verify(rec)
        assert result.status == NetworkInterventionStatus.PENDING

    def test_verify_on_applied_sets_verified(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:")
        rec = engine.apply(rec)
        rec = engine.verify(rec, measured_latency_ms=None)
        assert rec.status == NetworkInterventionStatus.VERIFIED

    def test_verify_precision_check_pass_on_good_measurement(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:", latency_ms=200.0)
        rec = engine.apply(rec)
        # Within 10% error → pass
        rec = engine.verify(rec, measured_latency_ms=205.0)
        assert rec.precision_check_pass is True

    def test_verify_precision_check_fail_on_bad_measurement(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:", latency_ms=200.0)
        rec = engine.apply(rec)
        # >20% error → fail
        rec = engine.verify(rec, measured_latency_ms=300.0)
        assert rec.precision_check_pass is False
        assert rec.status == NetworkInterventionStatus.CONFOUNDED
