class TestLatencyInjectionCommandStructure:
    def test_apply_generates_three_commands(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:", latency_ms=200.0)

        with patch.object(engine, "_run_cmd", wraps=engine._run_cmd) as mock_run:
            engine.apply(rec)
        assert mock_run.call_count == 3

    def test_apply_uses_correct_band_in_parent(self):
        """netem parent must be 1:<band>, not 1:10 or similar."""
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="2:", latency_ms=100.0)

        with patch.object(engine, "_run_cmd", wraps=engine._run_cmd) as mock_run:
            engine.apply(rec)

        cmds = _extract_cmds(mock_run)
        netem_cmd = cmds[1]  # second command: tc qdisc add ... netem
        # parent 1:2 must be in the command
        assert "parent" in netem_cmd
        parent_idx = netem_cmd.index("parent")
        assert netem_cmd[parent_idx + 1] == "1:2"

    def test_apply_uses_correct_band_as_handle(self):
        """netem handle must be <band>:, not 10: or similar."""
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="2:", latency_ms=100.0)

        with patch.object(engine, "_run_cmd", wraps=engine._run_cmd) as mock_run:
            engine.apply(rec)

        cmds = _extract_cmds(mock_run)
        netem_cmd = cmds[1]
        handle_idx = netem_cmd.index("handle")
        assert netem_cmd[handle_idx + 1] == "2:"

    def test_apply_filter_uses_correct_flowid(self):
        """u32 filter flowid must be 1:<band>."""
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="3:", latency_ms=50.0)

        with patch.object(engine, "_run_cmd", wraps=engine._run_cmd) as mock_run:
            engine.apply(rec)

        cmds = _extract_cmds(mock_run)
        filter_cmd = cmds[2]  # third command: tc filter add
        flowid_idx = filter_cmd.index("flowid")
        assert filter_cmd[flowid_idx + 1] == "1:3"

    def test_apply_sets_correct_latency_in_netem(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:", latency_ms=200.0, jitter_ms=10.0)

        with patch.object(engine, "_run_cmd", wraps=engine._run_cmd) as mock_run:
            engine.apply(rec)

        cmds = _extract_cmds(mock_run)
        netem_cmd = cmds[1]
        delay_idx = netem_cmd.index("delay")
        assert netem_cmd[delay_idx + 1] == "200.0ms"
        assert netem_cmd[delay_idx + 2] == "10.0ms"

    def test_apply_sets_status_applied(self):
        engine = NetworkInterventionEngine(dry_run=True)
        rec = _make_record(tc_handle="1:")
        result = engine.apply(rec)
        assert result.status == NetworkInterventionStatus.APPLIED

    def test_all_three_valid_bands_generate_structurally_valid_commands(self):
        """All bands 1, 2, 3 must produce commands that reference valid prio targets."""
        engine = NetworkInterventionEngine(dry_run=True)
        for band in (1, 2, 3):
            rec = _make_record(tc_handle=f"{band}:", latency_ms=100.0)
            with patch.object(engine, "_run_cmd", wraps=engine._run_cmd) as mock_run:
                engine.apply(rec)
            cmds = _extract_cmds(mock_run)
            # parent in netem command must be 1:<band>
            netem_cmd = cmds[1]
            parent_idx = netem_cmd.index("parent")
            assert netem_cmd[parent_idx + 1] == f"1:{band}"


