#!/usr/bin/env python3
"""Sprint 4.3.0 — generate the v2 datasets (dev, val, held-out CANDIDATE) deterministically.

Order guarantees (protocol §14):
  * refuses to write the held-out candidate unless artifacts/sprint4_3_0/protocol_v2.sha256 verifies against the
    original (pre-amendment) text of docs/EVALUATION_PROTOCOL_V2.md, i.e. the protocol existed first;
  * the held-out file is labelled CANDIDATE in datasets/rift_v2/heldout_status.json. It becomes FINAL_FROZEN only
    through scripts/sprint430_freeze.py after the independence verifier passes.
Never overwrites an existing dataset file whose bytes differ (unless --force-dev-val, which cannot touch held-out).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "src"))

from src.rift.scenarios import GENERATOR_VERSION, generator_v2 as G  # noqa: E402
from src.rift.scenarios.independence import verify_independence  # noqa: E402
from src.rift.scenarios.validators import validate_all  # noqa: E402

OUT = REPO_ROOT / "datasets" / "rift_v2"
PROTOCOL = REPO_ROOT / "docs" / "EVALUATION_PROTOCOL_V2.md"
PROTOCOL_HASH = REPO_ROOT / "artifacts" / "sprint4_3_0" / "protocol_v2.sha256"
FILES = {"dev": "dev.json", "val": "val.json", "held_out": "heldout_candidate.json"}


def original_protocol_text() -> bytes:
    t = PROTOCOL.read_text()
    i = t.find("### Amendment 1")
    head = t if i < 0 else t[:i] + "*(empty at registration)*\n"
    return head.encode()


def protocol_registered_first() -> bool:
    if not PROTOCOL_HASH.is_file():
        return False
    want = PROTOCOL_HASH.read_text().split()[0]
    return hashlib.sha256(original_protocol_text()).hexdigest() == want


def dumps(obj) -> bytes:
    return (json.dumps(obj, indent=1, sort_keys=True) + "\n").encode()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force-dev-val", action="store_true")
    ap.add_argument("--check", action="store_true",
                    help="regenerate in memory and compare with the files on disk; writes NOTHING (safe after freeze)")
    a = ap.parse_args()
    if not protocol_registered_first():
        print("REFUSED: pre-registered protocol hash does not verify; held-out candidate will not be generated.")
        return 2
    OUT.mkdir(parents=True, exist_ok=True)
    data = {s: G.generate_split(s) for s in ("dev", "val", "held_out")}
    qc = {s: validate_all(v) for s, v in data.items()}
    bad = {s: r["n_failed"] for s, r in qc.items() if r["n_failed"] or r["duplicate_ids"]}
    if bad:
        print("QC FAILED", bad)
        return 3
    ind = verify_independence(data)
    if not ind["ok"]:
        print("INDEPENDENCE FAILED", json.dumps(ind["leaks_for_protected"]))
        return 4
    if a.check:
        ok = True
        for s, scs in data.items():
            payload = {"dataset": f"rift_v2_{s}", "role": "CANDIDATE" if s == "held_out" else s.upper(),
                       "generator_version": GENERATOR_VERSION, "protocol_sha256_at_generation":
                       PROTOCOL_HASH.read_text().split()[0], "n_scenarios": len(scs), "scenarios": scs}
            same = (OUT / FILES[s]).read_bytes() == dumps(payload)
            ok &= same
            print(f"{s}: regenerated bytes {'IDENTICAL' if same else 'DIFFER'} to {FILES[s]}")
        return 0 if ok else 6
    hashes = {}
    for s, scs in data.items():
        payload = {"dataset": f"rift_v2_{s}", "role": "CANDIDATE" if s == "held_out" else s.upper(),
                   "generator_version": GENERATOR_VERSION, "protocol_sha256_at_generation":
                   PROTOCOL_HASH.read_text().split()[0], "n_scenarios": len(scs), "scenarios": scs}
        raw = dumps(payload)
        path = OUT / FILES[s]
        if path.exists() and path.read_bytes() != raw:
            if s == "held_out" or not a.force_dev_val:
                print(f"REFUSED to overwrite differing {path.name}")
                return 5
        path.write_bytes(raw)
        hashes[s] = {"file": FILES[s], "sha256": hashlib.sha256(raw).hexdigest(), "size_bytes": len(raw),
                     "n_scenarios": len(scs)}
    status = {"heldout_status": "CANDIDATE", "reason": "independence verified; freeze not yet performed",
              "file": FILES["held_out"], "sha256": hashes["held_out"]["sha256"]}
    (OUT / "heldout_status.json").write_bytes(dumps(status))
    manifest = {"generator_version": GENERATOR_VERSION, "datasets": hashes,
                "targets": {"dev": 150, "val": 60, "held_out": 90, "total": 300},
                "distinct_content_hash": {s: len({x["content_hash"] for x in v}) for s, v in data.items()},
                "distinct_template_id": {s: len({x["template_id"] for x in v}) for s, v in data.items()},
                "qc": {s: {"n": r["n"], "n_failed": r["n_failed"]} for s, r in qc.items()},
                "independence_ok": ind["ok"]}
    (OUT / "manifest.json").write_bytes(dumps(manifest))
    (OUT / "independence_report.json").write_bytes(dumps(ind))
    print(json.dumps(manifest, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
